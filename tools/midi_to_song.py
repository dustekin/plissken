#!/usr/bin/env python3
"""Convert a MIDI file into dsp/song.h, a note list for the Plissken parts.

Parts: 0 JUNO, 1 PIANO, 2 PRO-1, 3 GUITAR, 4 BASS, 5 LM-1 (note 0 kick, 1 snare, 2 hat), 6 CS-50.
Channel 1 is the bass. Channel 3 notes below 36 are the electric guitar's low riff notes, written
an octave under guitar range, so they are raised an octave; the rest of channel 3 is the CS-50.
Usage: midi_to_song.py file.mid [dsp/song.h]
"""
import sys
from pathlib import Path

import mido

JUNO, PIANO, PRO, GUITAR, BASS, DRUMS, CS50 = range(7)
DRUM_MAP = {36: 0, 38: 1, 45: 0, 54: 2, 88: 2}


def assign(channel, note):
    if channel == 9:
        return (DRUMS, DRUM_MAP[note]) if note in DRUM_MAP else None
    if channel == 4 and note == 88:
        return DRUMS, 2
    if channel in (4, 2):
        return JUNO, note
    if channel in (6, 7):
        return PRO, note
    if channel in (0, 5):
        return PIANO, note
    if channel == 1:
        return BASS, note
    if channel == 3:
        return (GUITAR, note + 12) if note < 36 else (CS50, note)
    return None


def collect(midi):
    notes = []
    for index, track in enumerate(midi.tracks):
        now = 0
        open_notes = {}
        for msg in track:
            now += msg.time
            if msg.type == "note_on" and msg.velocity > 0:
                open_notes[(msg.channel, msg.note)] = (now, msg.velocity)
            elif msg.type in ("note_off", "note_on") and (msg.channel, msg.note) in open_notes:
                start, velocity = open_notes.pop((msg.channel, msg.note))
                notes.append((index, msg.channel, msg.note, start, max(now - start, 1), velocity))
    return notes


def main():
    midi = mido.MidiFile(sys.argv[1])
    out = Path(sys.argv[2] if len(sys.argv) > 2 else "dsp/song.h")
    tempo = next((m.tempo for t in midi.tracks for m in t if m.type == "set_tempo"), 500000)
    ppq = midi.ticks_per_beat
    notes = collect(midi)
    events = {}
    for _, channel, note, start, duration, velocity in notes:
        target = assign(channel, note)
        if target:
            part, pitch = target
            key = (start, part, pitch)
            old = events.get(key, (0, 0))
            events[key] = (max(old[0], duration), max(old[1], velocity))
    rows = sorted((t, p, n, min(d, 65535), v) for (t, p, n), (d, v) in events.items())
    end = max(t + d for t, _, _, d, _ in rows)
    with out.open("w", newline="\n") as f:
        f.write("/* Generated by tools/midi_to_song.py; do not commit. */\n")
        f.write(f"#define SONG_PPQ {ppq}\n#define SONG_BPM {round(60000000 / tempo)}\n")
        f.write(f"#define SONG_TICKS {end}u\n#define SONG_EVENTS {len(rows)}\n")
        f.write("static const song_event_t song_events[SONG_EVENTS] = {\n")
        for t, p, n, d, v in rows:
            f.write(f"    {{{t}u, {d}u, {p}, {n}, {v}}},\n")
        f.write("};\n")
    counts = [sum(1 for r in rows if r[1] == p) for p in range(7)]
    print(f"{len(rows)} events, {end / ppq:.0f} beats, parts {counts} -> {out}")


if __name__ == "__main__":
    main()
