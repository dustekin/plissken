#!/usr/bin/env python3
"""Pack a supplied warning portrait as a small transparent grayscale RLE image."""
import argparse
from pathlib import Path

from PIL import Image


MAX_HEIGHT = 48


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="portrait PNG source")
    parser.add_argument("--out", type=Path, required=True, help="generated C header path")
    args = parser.parse_args()

    with Image.open(args.image) as source:
        width = max(1, round(source.width * MAX_HEIGHT / source.height))
        gray = source.convert("L").resize((width, MAX_HEIGHT), Image.Resampling.LANCZOS)

    indices = []
    for value in gray.getdata():
        if value < 24:
            indices.append(0)
        elif value < 92:
            indices.append(1)
        elif value < 168:
            indices.append(2)
        else:
            indices.append(3)

    rle = []
    position = 0
    while position < len(indices):
        color = indices[position]
        end = position + 1
        while end < len(indices) and indices[end] == color and end - position < 255:
            end += 1
        rle.extend((end - position, color))
        position = end

    lines = [
        "/* Generated by tools/pack_warning_portrait.py; source assets/vancleef2.png. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define WARNING_PORTRAIT_WIDTH {width}u",
        f"#define WARNING_PORTRAIT_HEIGHT {MAX_HEIGHT}u",
        f"#define WARNING_PORTRAIT_RLE_SIZE {len(rle)}u",
        "",
        f"static const uint8_t warning_portrait_rle[{len(rle)}] = {{",
    ]
    for offset in range(0, len(rle), 24):
        lines.append("    " + ", ".join(str(value) for value in rle[offset:offset + 24]) + ",")
    lines.extend(("};", ""))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="ascii")
    print(f"Packed warning portrait as {width}x{MAX_HEIGHT}, {len(rle)} RLE bytes.")


if __name__ == "__main__":
    main()
