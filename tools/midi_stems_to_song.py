#!/usr/bin/env python3
"""Combine part-separated MIDI stems into a generated Plissken song header."""
import argparse
from pathlib import Path

import mido

from midi_to_song import collect

PART_JUNO = 0
PART_PIANO = 1
PART_BASS = 4
PART_DRUMS = 5
DEFAULT_DRUM_MAP = {36: 0, 38: 1, 42: 2, 45: 0, 54: 2, 88: 2}


def load_stem(path, part):
    midi = mido.MidiFile(path)
    tempo = next(
        (message.tempo for track in midi.tracks for message in track if message.type == "set_tempo"),
        500000,
    )
    events = []
    for _, _, note, start, duration, velocity in collect(midi):
        events.append((start, duration, part, note, velocity))
    if not events:
        raise ValueError(f"No MIDI notes found in {path}")
    return midi.ticks_per_beat, tempo, events


def repeat_drums(events, source_ticks, end_tick):
    if source_ticks <= 0:
        raise ValueError("Drum loop duration must be positive")
    return [
        (start + offset, duration, part, note, velocity)
        for offset in range(0, end_tick, source_ticks)
        for start, duration, part, note, velocity in events
        if start + offset < end_tick
    ]


def combine(juno_path, piano_path, bass_path, drums_path, drum_loop_ticks=None):
    source_stems = [
        load_stem(juno_path, PART_JUNO),
        load_stem(piano_path, PART_PIANO),
        load_stem(bass_path, PART_BASS),
    ]
    ppqs = {stem[0] for stem in source_stems}
    tempos = {stem[1] for stem in source_stems}
    drum_ppq, drum_tempo, drums = load_stem(drums_path, PART_DRUMS)
    ppqs.add(drum_ppq)
    tempos.add(drum_tempo)
    if len(ppqs) != 1:
        raise ValueError(f"MIDI stems have different PPQ values: {sorted(ppqs)}")
    if len(tempos) != 1:
        raise ValueError(f"MIDI stems have different tempos: {sorted(tempos)}")

    pitched = [event for _, _, stem_events in source_stems for event in stem_events]
    mapped_drums = []
    for start, duration, part, note, velocity in drums:
        if note in DEFAULT_DRUM_MAP:
            mapped_drums.append((start, duration, part, DEFAULT_DRUM_MAP[note], velocity))
    if not mapped_drums:
        raise ValueError("The drum stem has no supported kick, snare or hat notes")
    end_tick = max(start + duration for start, duration, *_ in pitched)
    loop_ticks = drum_loop_ticks or max(start + duration for start, duration, *_ in mapped_drums)
    events = pitched + repeat_drums(mapped_drums, loop_ticks, end_tick)
    events.sort(key=lambda event: (event[0], event[2], event[3]))
    return ppqs.pop(), tempos.pop(), events


def write_header(path, ppq, tempo, events):
    end = max(start + duration for start, duration, *_ in events)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="\n") as output:
        output.write("/* Generated by tools/midi_stems_to_song.py; do not commit reference MIDI. */\n")
        output.write(f"#define SONG_PPQ {ppq}\n")
        output.write(f"#define SONG_BPM {round(60000000 / tempo)}u\n")
        output.write(f"#define SONG_TICKS {end}u\n")
        output.write(f"#define SONG_EVENTS {len(events)}\n")
        output.write("static const song_event_t song_events[SONG_EVENTS] = {\n")
        for start, duration, part, note, velocity in events:
            output.write(f"    {{{start}u, {min(duration, 65535)}u, {part}, {note}, {velocity}}},\n")
        output.write("};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--juno", required=True, type=Path)
    parser.add_argument("--piano", required=True, type=Path)
    parser.add_argument("--bass", required=True, type=Path)
    parser.add_argument("--drums", required=True, type=Path)
    parser.add_argument("--drum-loop-ticks", type=int)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    ppq, tempo, events = combine(
        args.juno,
        args.piano,
        args.bass,
        args.drums,
        args.drum_loop_ticks,
    )
    write_header(args.output, ppq, tempo, events)
    counts = {part: sum(event[2] == part for event in events) for part in (0, 1, 4, 5)}
    print(f"{len(events)} events, source parts {counts} -> {args.output}")


if __name__ == "__main__":
    main()
