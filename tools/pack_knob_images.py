#!/usr/bin/env python3
"""Pack user-provided knob portraits as compact grayscale RLE images."""
import argparse
from pathlib import Path
from statistics import median

from PIL import Image


def pack_image(path):
    with Image.open(path) as source:
        gray = source.convert("L")
        width, height = gray.size
        pixels = list(gray.getdata())

    corners = [
        pixels[0],
        pixels[width - 1],
        pixels[(height - 1) * width],
        pixels[height * width - 1],
    ]
    border = (
        pixels[:width]
        + pixels[-width:]
        + pixels[::width]
        + pixels[width - 1::width]
    )
    background = min(median(corners), median(border))
    threshold = min(255, background + 12)

    indices = []
    for value in pixels:
        if value <= threshold:
            indices.append(0)
        else:
            indices.append(min(3, 1 + (value - threshold - 1) * 3 // (256 - threshold)))

    rle = []
    position = 0
    while position < len(indices):
        color = indices[position]
        end = position + 1
        while end < len(indices) and indices[end] == color and end - position < 255:
            end += 1
        rle.extend((end - position, color))
        position = end
    return width, height, rle


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("images", nargs=4, type=Path, help="four ordered PNG source images")
    parser.add_argument("--out", type=Path, required=True, help="generated C header path")
    args = parser.parse_args()

    packed = [pack_image(path) for path in args.images]
    width, height = packed[0][:2]
    if any((image_width, image_height) != (width, height)
           for image_width, image_height, _ in packed):
        parser.error("all four images must have the same dimensions")

    max_size = max(len(rle) for _, _, rle in packed)
    lines = [
        "/* Generated by tools/pack_knob_images.py from user-provided artwork. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define KNOB_IMAGE_WIDTH {width}u",
        f"#define KNOB_IMAGE_HEIGHT {height}u",
        f"#define KNOB_IMAGE_MAX_RLE_SIZE {max_size}u",
        "",
        "static const uint16_t knob_image_rle_sizes[4] = {",
        "    " + ", ".join(f"{len(rle)}u" for _, _, rle in packed),
        "};",
        "",
        f"static const uint8_t knob_image_rle[4][{max_size}] = {{",
    ]
    for _, _, rle in packed:
        lines.append("    {")
        for offset in range(0, len(rle), 24):
            lines.append("        " + ", ".join(str(value) for value in rle[offset:offset + 24]) + ",")
        lines.append("    },")
    lines.extend(("};", ""))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="ascii")
    print(f"Packed four knob portraits as {width}x{height}, {sum(len(rle) for _, _, rle in packed)} RLE bytes.")


if __name__ == "__main__":
    main()
