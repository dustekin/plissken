#!/usr/bin/env python3
"""Pack the 240x144 Plissken startup PNG as a compact four-color RGB565/RLE header."""
import argparse
from pathlib import Path

from PIL import Image


WIDTH = 240
HEIGHT = 144
PALETTE = ((0, 0, 0), (0, 220, 210), (255, 145, 0), (30, 115, 255))


def rgb565(color):
    red, green, blue = color
    return ((red >> 3) << 11) | ((green >> 2) << 5) | (blue >> 3)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("image", type=Path, help="240x144 PNG source")
    parser.add_argument("--out", type=Path, required=True, help="generated C header path")
    args = parser.parse_args()

    with Image.open(args.image) as source:
        if source.size != (WIDTH, HEIGHT):
            raise ValueError(f"{args.image}: expected {WIDTH}x{HEIGHT}, got {source.width}x{source.height}")
        palette_image = Image.new("P", (1, 1))
        palette_data = [channel for color in PALETTE for channel in color]
        palette_image.putpalette(palette_data + [0] * (768 - len(palette_data)))
        indexed = source.convert("RGB").quantize(palette=palette_image, dither=Image.Dither.NONE)
        indices = list(indexed.getdata())
        palette = [rgb565(color) for color in PALETTE]
    rle = []
    for y in range(HEIGHT):
        row = indices[y * WIDTH:(y + 1) * WIDTH]
        x = 0
        while x < WIDTH:
            color = row[x]
            end = x + 1
            while end < WIDTH and row[end] == color and end - x < 255:
                end += 1
            rle.extend((end - x, color))
            x = end

    lines = [
        "/* Generated by tools/pack_splash.py; source assets/startup.png. */",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define STARTUP_SPLASH_WIDTH {WIDTH}u",
        f"#define STARTUP_SPLASH_HEIGHT {HEIGHT}u",
        f"#define STARTUP_SPLASH_RLE_SIZE {len(rle)}u",
        "",
        f"static const uint16_t startup_splash_palette[{len(PALETTE)}] = {{",
        "    " + ", ".join(f"0x{color:04x}u" for color in palette),
        "};",
        "",
        f"static const uint8_t startup_splash_rle[{len(rle)}] = {{",
    ]
    for offset in range(0, len(rle), 24):
        lines.append("    " + ", ".join(str(value) for value in rle[offset:offset + 24]) + ",")
    lines.extend(("};", ""))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="ascii")
    print(f"Packed {WIDTH}x{HEIGHT} splash into {len(rle)} RLE bytes and {len(PALETTE)} RGB565 colors.")


if __name__ == "__main__":
    main()
