#!/usr/bin/env python3
"""Generate the dense, playback-only Escape arrangement from its converted MIDI."""
import argparse
from collections import Counter
from pathlib import Path

import song_to_sequence as sequence

ROOT = Path(__file__).resolve().parents[1]


def thin_piano_octaves(events):
    piano = {(event["step"], event["note"], event["duration"])
             for event in events if event["part"] == 6}
    return [
        event for event in events
        if event["part"] != 6
        or (event["step"], event["note"] + 12, event["duration"]) not in piano
    ]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("song", type=Path)
    parser.add_argument("samples", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--thin-piano-octaves", action="store_true",
                        help="omit the lower note of matched piano octave pairs")
    args = parser.parse_args()

    sequence.PITCH_PARTS[3] = (2, 3)
    sequence.PART_ORDER = (5, 0, 1, 2, 3, 4, 6)
    sequence.MAX_EVENTS = 10000
    sequence.MAX_VOICES = 100
    sequence.MAX_PITCH_DURATION_STEPS = 64
    pitched = (0, 1, 2, 3, 4, 6)
    bpm, bars, events, stats = sequence.analyze(
        args.song,
        args.samples,
        included_parts=(0, 1, 2, 3, 4, 5, 6),
        polyphonic_parts=pitched,
        pitch_grid_overrides={part: 1 for part in pitched},
    )
    if sum(stats["voice_drop_counts"].values()) or sum(stats["event_cap_drop_counts"].values()):
        raise ValueError("Escape conversion discarded events before playback")
    # Keep the original rotating order for the remaining simultaneous notes.
    events = [event for event in events if event["part"] != 4]
    if args.thin_piano_octaves:
        events = thin_piano_octaves(events)
    factory = (ROOT / "dsp" / "escape_sequence.h").read_text()
    if bpm != sequence.macro_value(factory, "ESCAPE_SEQUENCE_BPM") or bars != sequence.macro_value(
        factory, "ESCAPE_SEQUENCE_BARS"
    ):
        raise ValueError("Escape source timing does not match the saved factory song")
    for event in events:
        if event["part"] == 6:
            event["instrument"] = 1
        elif event["part"] == 3:
            event["variant"] = 1
    if any(events[i]["step"] > events[i + 1]["step"] for i in range(len(events) - 1)):
        raise ValueError("Escape playback events must be ordered by onset")

    with args.output.open("w", newline="\n") as output:
        option = " --thin-piano-octaves" if args.thin_piano_octaves else ""
        output.write(f"/* Generated by tools/generate_escape_playback.py{option}; do not edit. */\n")
        output.write(f"#define ESCAPE_REBUILD_EVENT_COUNT {len(events)}u\n")
        output.write("static const uint32_t escape_rebuild_events[ESCAPE_REBUILD_EVENT_COUNT] = {\n")
        for offset in range(0, len(events), 4):
            packed = ", ".join(
                f"{sequence.encode_event(event)}u"
                for event in events[offset:offset + 4]
            )
            output.write(f"    {packed},\n")
        output.write("};\n")
    print(f"{len(events)} grouped events, {bars} bars at {bpm} BPM; "
          f"parts {dict(Counter(event['part'] for event in events))}; "
          f"{sum(stats['merged_counts'].values())} merged, "
          f"{sum(stats['ignored_counts'].values())} ignored")


if __name__ == "__main__":
    main()
